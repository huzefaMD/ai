#Understanding


# print() with text — always use quotes
print("Hello HuzefAI!")

# print() with a number — no quotes needed
print(4999)

# print() with nothing — prints a blank line
print()

# print() multiple things separated by comma
print("Course:", "AWS", "Price:", 4999)
# Output: Course: AWS Price: 4999

#The end Parameter

# Default — new line after each print
print("Hello")
print("World")
# Output:
# Hello
# World

# With end="" — no new line (used in streaming!)
print("Hello", end="")
print(" World")
# Output:
# Hello World





